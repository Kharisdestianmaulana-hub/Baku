let currentLang = localStorage.getItem('baku_lang') || 'id';

window.t = function(textId) {
    if (currentLang === 'id') return textId;
    return DICT_EN[textId] || textId;
};

function initI18n() {
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, null, false);
    const textNodes = [];
    let node;
    while(node = walker.nextNode()) {
        // Jangan sentuh isi kanvas editor atau elemen yang ditandai no-translate
        if (node.parentElement && (node.parentElement.closest('#quill-container') || node.parentElement.closest('.no-translate'))) continue;
        
        const text = node.nodeValue.trim();
        if (text.length > 0 && DICT_EN[text]) {
            textNodes.push({ node: node, orig: text });
        }
    }

    // Scan placeholder pada input
    const inputs = document.querySelectorAll('input[placeholder]');

    // Scan teks di dalam <option>
    const options = document.querySelectorAll('option');

    // Scan atribut title pada elemen (untuk tooltip)
    const titledEls = document.querySelectorAll('[title]');

    window._i18nNodes = textNodes;
    window._i18nInputs = inputs;
    window._i18nOptions = Array.from(options);
    window._i18nTitles = Array.from(titledEls);
    
    applyLang(currentLang);
}

function applyLang(lang) {
    currentLang = lang;
    localStorage.setItem('baku_lang', lang);

    // Terjemahkan Text Nodes
    window._i18nNodes.forEach(item => {
        let text = item.orig;
        if (lang === 'en') text = DICT_EN[text] || text;
        item.node.nodeValue = text;
    });

    // Terjemahkan Placeholder
    window._i18nInputs.forEach(input => {
        if (!input.dataset.origPlaceholder) input.dataset.origPlaceholder = input.placeholder;
        let p = input.dataset.origPlaceholder;
        if (lang === 'en') p = DICT_EN[p] || p;
        input.placeholder = p;
    });

    // Terjemahkan Option
    window._i18nOptions.forEach(opt => {
        if (!opt.dataset.origText) opt.dataset.origText = opt.textContent.trim();
        let text = opt.dataset.origText;
        if (lang === 'en') text = DICT_EN[text] || text;
        opt.textContent = text;
    });

    // Terjemahkan atribut title (tooltip)
    window._i18nTitles.forEach(el => {
        if (!el.dataset.origTitle) el.dataset.origTitle = el.getAttribute('title');
        let t = el.dataset.origTitle;
        if (lang === 'en') t = DICT_EN[t] || t;
        el.setAttribute('title', t);
    });
}

document.addEventListener('DOMContentLoaded', () => {
    initI18n();
    
    const langSelect = document.getElementById('setting-lang');
    if (langSelect) {
        langSelect.value = currentLang;
        langSelect.addEventListener('change', (e) => {
            applyLang(e.target.value);
            if (typeof renderRecentDocs === 'function') renderRecentDocs();
        });
    }
});
